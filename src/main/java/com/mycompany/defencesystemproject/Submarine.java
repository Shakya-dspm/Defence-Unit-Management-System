    private void btnSonarOpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSonarOpActionPerformed
        // TODO add your handling code here:
        if (energyLevel > 0) {
            energyLevel -= 3;
            if(energyLevel <= 0) energyLevel = 0;
            sliderEnergy.setValue(energyLevel);
        } else {
            JOptionPane.showMessageDialog(null, "Out of Energy", "Warning", JOptionPane.WARNING_MESSAGE);
        }

        if (oxygenLevel < 70) {
            JOptionPane.showMessageDialog(null, "Oxygen Level is Low", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            oxygenLevel -= 4;
            if (oxygenLevel < 0)oxygenLevel = 0;
            sliderOxygen.setValue(oxygenLevel);
        }
    }//GEN-LAST:event_btnSonarOpActionPerformed

