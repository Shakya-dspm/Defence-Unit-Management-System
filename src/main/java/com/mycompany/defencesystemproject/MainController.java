    private void getStrengthData() {
        String totAmmoCount = Integer.toString(helicopter.getAmmoCount() + submarine.getAmmoCount() + tank.getAmmoCount());
        int totEnergy = ((helicopter.getEnergyLevel() + submarine.getEnergyLevel() + tank.getEnergyLevel()) * 100) / 300;
        String energyStatus = totEnergy >= 75 ? "HIGH" : totEnergy >= 35 ? "MID" : "LOW";
        String totSoilderCount = Integer.toString(helicopter.getSoilderAmount() + submarine.getSoilderAmount() + tank.getSoilderAmount());

        lblresultAmmo.setText(totAmmoCount);
        lblresultSoilder.setText(totSoilderCount);
        lblresultEnergy.setText(energyStatus);
        
        switch(energyStatus){
            case "HIGH" :
                lblresultEnergy.setForeground(new Color(125, 150, 74));
                break;
            case "MID" :
                lblresultEnergy.setForeground(new Color(201, 102, 40));
                break;
            case "LOW" :
                lblresultEnergy.setForeground(new Color(191, 54, 36));
                break;
            default : 
                lblresultEnergy.setText("-");
                break;
        }
    }
    
