    private void btnSendActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSendActionPerformed
        // TODO add your handling code here:
        String massage = txtfTypeArea.getText();
        String sender = this.getClass().getSimpleName();

        if (massage == null || massage.isBlank()) {
            JOptionPane.showMessageDialog(null, "You have not type anything yet...", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            if (chkbxSendPrivate.isSelected()) {
                int selectedDefenceIndex = styleComboBox1.getSelectedIndex();

                switch (selectedDefenceIndex) {
                    case 0:
                        JOptionPane.showMessageDialog(null, "You have not Select any Defence yet...", "Warning", JOptionPane.WARNING_MESSAGE);
                        break;
                    case 1:
                        txtBoard.appendMessage(sender + " : " + massage);
                        helicopter.setMassageBoard(sender, massage);
                        txtfTypeArea.setText("");
                        break;
                    case 2:
                        txtBoard.appendMessage(sender + " : " + massage);
                        tank.setMassageBoard(sender, massage);
                        txtfTypeArea.setText("");
                        break;
                    case 3:
                        txtBoard.appendMessage(sender + " : " + massage);
                        submarine.setMassageBoard(sender, massage);
                        txtfTypeArea.setText("");
                        break;
                }
            } else {
                txtBoard.appendMessage(sender + " : " + massage);
                helicopter.setMassageBoard(sender, massage);
                tank.setMassageBoard(sender, massage);
                submarine.setMassageBoard(sender, massage);
                txtfTypeArea.setText("");
            }
        }
    }//GEN-LAST:event_btnSendActionPerformed

