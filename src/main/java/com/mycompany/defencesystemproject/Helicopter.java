    private void btnShootActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnShootActionPerformed
        // TODO add your handling code here:
        if (getAmmoCount() > 0 && energyLevel > 0) {
            if (!isShootHolding) {
                int currentAmmo = getAmmoCount();
                if (currentAmmo > 0) {
                    sprAmmoCount.setValue(currentAmmo - 1);
                    sliderEnergy.setValue(--energyLevel);
                }
            }
        } else {
            if (getAmmoCount() == 0) {
                JOptionPane.showMessageDialog(null, "Out of Ammo", "Warning", JOptionPane.WARNING_MESSAGE);
            }
            if (energyLevel == 0) {
                JOptionPane.showMessageDialog(null, "Out of Energy", "Warning", JOptionPane.WARNING_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnShootActionPerformed

    private void btnShootMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnShootMousePressed
        // TODO add your handling code here:
        if (btnShoot.isEnabled() && SwingUtilities.isLeftMouseButton(evt)) {
            isShootHolding = false;
            holdTimer.restart(); // Start the 300ms hold countdown
        }
    }//GEN-LAST:event_btnShootMousePressed

    private void btnShootMouseReleased(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnShootMouseReleased
        // TODO add your handling code here:
        if (SwingUtilities.isLeftMouseButton(evt)) {
            holdTimer.stop();      // Cancel hold timer if released early (single click)
            rapidFireTimer.stop(); // Stop rapid fire if it was running
            isShootHolding = false;
        }
    }//GEN-LAST:event_btnShootMouseReleased

    private void btnMissileOpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMissileOpActionPerformed
        // TODO add your handling code here:
        if(energyLevel > 0){
          energyLevel -= 3;
          if(energyLevel <= 0) energyLevel = 0;
          sliderEnergy.setValue(energyLevel);
        }else{
            JOptionPane.showMessageDialog(null, "Out of Energy", "Warning", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnMissileOpActionPerformed

