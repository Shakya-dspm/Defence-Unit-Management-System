    private void btnMiissileOpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMiissileOpActionPerformed
        // TODO add your handling code here:
        if(energyLevel > 0){
          energyLevel -= 3;
          if(energyLevel <= 0) energyLevel = 0;
          sliderEnergy.setValue(energyLevel);
        }else{
            JOptionPane.showMessageDialog(null, "Out of Energy", "Warning", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnMiissileOpActionPerformed

    private void btnSendActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSendActionPerformed
        // TODO add your handling code here:
        String massage = txtfTypeArea.getText();
        String sender = this.getClass().getSimpleName();

        if (massage == null || massage.isBlank()) {
            JOptionPane.showMessageDialog(null, "You have not type anything yet...", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            mainController.getMassage(sender, massage);
            txtaBoard.appendMessage(sender + " : " + massage);
        }
    }//GEN-LAST:event_btnSendActionPerformed

