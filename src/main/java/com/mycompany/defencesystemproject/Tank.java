    public Tank(MainController mainController) {

        this.mainController = mainController;

        initComponents();
        
        for (java.awt.event.MouseListener ml : sliderEnergy.getMouseListeners()) {
            sliderEnergy.removeMouseListener(ml);
        }
        for (java.awt.event.MouseMotionListener mml : sliderEnergy.getMouseMotionListeners()) {
            sliderEnergy.removeMouseMotionListener(mml);
        }
        
        Timer energyDorpTimer = new Timer(4000, (java.awt.event.ActionEvent e) -> {
            int currentValue = sliderEnergy.getValue();
            
            if(currentValue > sliderEnergy.getMinimum()){
                sliderEnergy.setValue(--energyLevel);
            }
        });
        energyDorpTimer.start();
        
        Timer sliderPollTimer = new Timer(1000, (java.awt.event.ActionEvent e) -> {
            int continuousValue = sliderEnergy.getValue();
            energyLevel = continuousValue;
            mainController.readData();
        });
        
        sliderPollTimer.start();

        rapidFireTimer = new Timer(100, (java.awt.event.ActionEvent e) -> {
            int currentAmmo = getAmmoCount();
            if (currentAmmo > 0 && energyLevel > 0) {
                int newAmmo = Math.max(0, currentAmmo - 1);
                sprAmmoCount.setValue(newAmmo);
                sliderEnergy.setValue(--energyLevel);
                if (newAmmo == 0) {
                    rapidFireTimer.stop();
                    isShootHolding = false;
                    JOptionPane.showMessageDialog(null, "Out of Ammo", "Warning", JOptionPane.WARNING_MESSAGE);
                }
            } else {
                rapidFireTimer.stop();
                isShootHolding = false;
            }
        });

        holdTimer = new Timer(300, (java.awt.event.ActionEvent e) -> {
            isShootHolding = true;
            if (getAmmoCount() > 0) {
                rapidFireTimer.start();
            }
        });
        holdTimer.setRepeats(false);
    }

